pub(crate) const EVIDENCE_SECTIONS: [&str; 7] = [
    "Tier",
    "Task",
    "Fail-first test",
    "Checks",
    "Safety proof",
    "Runtime evidence",
    "Gaps",
];

const SKIP_MARKERS: [&str; 5] = [
    "[skip ci]",
    "[ci skip]",
    "[no ci]",
    "[skip actions]",
    "[actions skip]",
];

pub(crate) fn commit_message_problems(
    message: &str,
    types: &[String],
    scopes: &[String],
) -> Vec<String> {
    let lines: Vec<&str> = message
        .lines()
        .filter(|line| !line.starts_with('#'))
        .collect();
    let mut problems = Vec::new();
    match lines.iter().find(|line| !line.trim().is_empty()) {
        None => problems.push("the message is empty".to_string()),
        Some(subject) if subject.starts_with("Merge ") => {}
        Some(subject) => problems.extend(subject_problem(subject, types, scopes)),
    }
    for line in &lines {
        let lowered = line.trim().to_lowercase();
        if lowered.starts_with("co-authored-by:") {
            problems.push("it has a co-author line".to_string());
        }
        if lowered.contains("generated with") || lowered.contains("generated by") {
            problems.push("it has an agent attribution line".to_string());
        }
        if SKIP_MARKERS.iter().any(|marker| lowered.contains(marker))
            || lowered.starts_with("skip-checks:")
        {
            problems.push("it tells CI to skip the commit".to_string());
        }
    }
    problems
        .into_iter()
        .map(|problem| {
            format!("Commit message: {problem}. Use \"{{type}}({{scope}}): {{summary}}\" with no co-author or attribution lines.")
        })
        .collect()
}

fn subject_problem(subject: &str, types: &[String], scopes: &[String]) -> Option<String> {
    let Some((header, summary)) = subject.split_once(": ") else {
        return Some(format!("the subject \"{subject}\" lacks \"{{type}}: \""));
    };
    if summary.trim().is_empty() {
        return Some("the subject has no summary".to_string());
    }
    let header = header.strip_suffix('!').unwrap_or(header);
    let (kind, scope) = match header.split_once('(') {
        Some((kind, rest)) => match rest.strip_suffix(')') {
            Some(scope) => (kind, Some(scope)),
            None => return Some(format!("the scope in \"{header}\" is not closed")),
        },
        None => (header, None),
    };
    if !types.iter().any(|allowed| allowed == kind) {
        return Some(format!(
            "the type \"{kind}\" is not one of {}",
            types.join(", ")
        ));
    }
    if let Some(scope) = scope
        && !scopes.iter().any(|allowed| allowed == scope)
    {
        return Some(format!(
            "the scope \"{scope}\" is not in checks.toml commit.scopes"
        ));
    }
    None
}

fn section_bodies(body: &str) -> Vec<(String, String)> {
    let mut sections: Vec<(String, String)> = Vec::new();
    for line in body.lines() {
        if let Some(title) = line.strip_prefix("## ") {
            sections.push((title.trim().to_string(), String::new()));
        } else if let Some((_, content)) = sections.last_mut() {
            content.push_str(line);
            content.push('\n');
        }
    }
    sections
}

fn without_html_comments(text: &str) -> String {
    let mut result = String::new();
    let mut rest = text;
    while let Some(start) = rest.find("<!--") {
        result.push_str(&rest[..start]);
        match rest[start..].find("-->") {
            Some(end) => rest = &rest[start + end + 3..],
            None => return result,
        }
    }
    result.push_str(rest);
    result
}

pub(crate) fn evidence_bundle_problems(body: &str) -> Violations {
    let sections = section_bodies(body);
    let mut violations = Violations::new();
    for required in EVIDENCE_SECTIONS {
        let Some((_, content)) = sections.iter().find(|(title, _)| title == required) else {
            violations.push(format!(
                "The pull request body lacks the {required} section. Use .github/pull_request_template.md."
            ));
            continue;
        };
        let content = without_html_comments(content);
        if content.trim().is_empty() {
            violations.push(format!(
                "The pull request body has an empty {required} section. Fill it in, or write \"Not applicable\" with a reason."
            ));
        }
        if let Some((_, placeholder)) = placeholders_in(&content).first() {
            violations.push(format!(
                "The pull request body section {required} still holds the placeholder <{placeholder}>. Fill it in."
            ));
        }
    }
    violations
}

pub(crate) fn declares_no_behavior_change(body: &str) -> bool {
    body.lines().any(|line| {
        line.split_once("No behavior change:")
            .is_some_and(|(_, reason)| !reason.trim().is_empty())
    })
}

pub(crate) fn behavior_has_test_problems(
    changes: &[FileChange],
    body: &str,
    settings: &Settings,
) -> Result<Violations, String> {
    let sources = glob_set(&settings.behavior_source)?;
    let tests = glob_set(&settings.behavior_tests)?;
    let changes_tests = changes.iter().any(|change| tests.is_match(&change.path));
    let changes_source = changes
        .iter()
        .any(|change| sources.is_match(&change.path) && !tests.is_match(&change.path));
    let violates = changes_source && !changes_tests && !declares_no_behavior_change(body);
    Ok(if violates {
        vec![
            "This pull request changes source files but no tests. Add a fail-first test, or state \"No behavior change: {reason}\" in the body."
                .to_string(),
        ]
    } else {
        Vec::new()
    })
}

