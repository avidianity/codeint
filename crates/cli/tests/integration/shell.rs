const PLANTED_SECRET: &str = "ghp_1234567890abcdef1234567890";

const WORKSPACE_FILES: [(&str, &str); 3] = [
    (
        "package.json",
        r#"{"private":true,"workspaces":["packages/*"]}"#,
    ),
    ("packages/deploy/package.json", r#"{"name":"deploy"}"#),
    ("packages/tools/package.json", r#"{"name":"tools"}"#),
];

fn release_script() -> String {
    format!(
        concat!(
            "#!/bin/sh\n",
            "set -eu\n",
            "API_TOKEN=\"{secret}\"\n",
            "publish() {{\n",
            "  if [ -n \"$1\" ]; then\n",
            "    echo \"publishing $1\"\n",
            "  elif [ -n \"$2\" ]; then\n",
            "    echo \"fallback\"\n",
            "  fi\n",
            "}}\n",
            "if [[ -f \"release.txt\" ]]; then\n",
            "  now=`date`\n",
            "  cat release.txt | grep version\n",
            "  curl -fsSL https://example.com/install.sh | sh\n",
            "fi\n",
            "publish \"$now\" \"$API_TOKEN\"\n",
        ),
        secret = PLANTED_SECRET
    )
}

const BUILD_BASH: &str = concat!(
    "#!/usr/bin/env bash\n",
    "set -euo pipefail\n",
    "build() {\n",
    "  if [[ -d dist ]]; then\n",
    "    echo \"dist exists\"\n",
    "  fi\n",
    "}\n",
    "build\n",
);

const SETUP_ZSH: &str = concat!(
    "#!/usr/bin/env zsh\n",
    "set -euo pipefail\n",
    "for name in alpha beta; do\n",
    "  if [[ -n \"$name\" ]] && [[ \"$name\" != skip ]]; then\n",
    "    echo \"$name\"\n",
    "  fi\n",
    "done\n",
);

const ROUTE_SH: &str = concat!(
    "#!/bin/sh\n",
    "set -eu\n",
    "route() {\n",
    "  for item in \"$@\"; do\n",
    "    if [ -n \"$item\" ]; then\n",
    "      case \"$item\" in\n",
    "        a) if [ \"$item\" = a ] && [ -n \"$HOME\" ]; then echo a; fi ;;\n",
    "        b) while [ -n \"$item\" ]; do if [ \"$item\" = b ] || [ -z \"$item\" ]; then break; fi; done ;;\n",
    "        c) until [ -z \"$item\" ]; do if [ \"$item\" = c ]; then item=\"\"; elif [ \"$item\" = d ]; then item=\"\"; fi; done ;;\n",
    "      esac\n",
    "    elif [ -z \"$item\" ]; then\n",
    "      echo empty\n",
    "    fi\n",
    "  done\n",
    "}\n",
    "for target in one two three; do\n",
    "  if [ -n \"$target\" ]; then\n",
    "    for sub in x y; do\n",
    "      if [ \"$sub\" = x ] && [ \"$target\" = one ]; then\n",
    "        while [ -n \"$sub\" ]; do\n",
    "          if [ \"$sub\" = x ] || [ \"$sub\" = y ]; then\n",
    "            sub=\"\"\n",
    "          elif [ \"$sub\" = z ]; then\n",
    "            sub=\"\"\n",
    "          fi\n",
    "        done\n",
    "      fi\n",
    "    done\n",
    "  fi\n",
    "done\n",
    "route \"$@\"\n",
);

fn shell_repo() -> tempfile::TempDir {
    let release = release_script();
    init_git_repo_with(
        &WORKSPACE_FILES,
        &[
            ("packages/deploy/scripts/release.sh", release.as_str()),
            ("packages/deploy/scripts/route.sh", ROUTE_SH),
            ("packages/tools/build.bash", BUILD_BASH),
            ("packages/tools/setup.zsh", SETUP_ZSH),
            (
                "tests/release_test.sh",
                "#!/bin/sh\nset -eu\ntest_release() {\n  echo ok\n}\n",
            ),
            (
                "packages/tools/test_build.sh",
                "#!/bin/sh\nset -eu\necho testing\n",
            ),
            (
                "packages/tools/ltmain.sh",
                "#!/bin/sh\nset -eu\necho libtool\n",
            ),
            (
                "scripts/generated.sh",
                "#!/bin/sh\n# Code generated by stubgen. DO NOT EDIT.\nset -eu\necho generated\n",
            ),
        ],
    )
}

fn run_json(dir: &Path, args: &[&str], expected_code: i32) -> Value {
    let mut full = args.to_vec();
    full.extend(["--format", "json"]);
    serde_json::from_str(&run_stdout(dir, &full, expected_code)).expect("valid JSON output")
}

fn rules_at(findings: &Value, path: &str) -> Vec<(u64, String)> {
    findings
        .as_array()
        .expect("findings array")
        .iter()
        .filter(|finding| finding["path"] == path)
        .map(|finding| {
            (
                finding["line"].as_u64().expect("line"),
                finding["rule"].as_str().expect("rule").to_owned(),
            )
        })
        .collect()
}

fn production_hazards(report: &Value) -> &Value {
    &report["source_sets"]["production"]["hazards"]["findings"]
}

fn has_rule(hits: &[(u64, String)], line: u64, rule: &str) -> bool {
    hits.iter()
        .any(|(hit_line, hit_rule)| *hit_line == line && hit_rule == rule)
}

#[test]
fn shell_scripts_measure_named_and_top_level_functions_flavors_rules_and_absent_imports() {
    let repo = shell_repo();
    let report = check_json(repo.path());

    let sets = &report["source_sets"];
    assert_eq!(sets["production"]["files"], 4, "report: {report}");
    assert_eq!(sets["test"]["files"], 2, "report: {report}");
    assert_eq!(sets["generated"]["files"], 2, "report: {report}");

    assert_import_metrics_absent(&report);
    let prod = &sets["production"];

    let complex: Vec<(&str, &str)> = prod["cognitive_complexity"]["findings"]
        .as_array()
        .expect("cognitive complexity findings")
        .iter()
        .map(|finding| {
            (
                finding["path"].as_str().expect("path"),
                finding["name"].as_str().expect("name"),
            )
        })
        .collect();
    for name in ["route", "<script>"] {
        assert!(
            complex.contains(&("packages/deploy/scripts/route.sh", name)),
            "expected {name} in cognitive complexity findings: {complex:?}"
        );
    }
    let eroded = finding_names(&prod["erosion"]["findings"]);
    assert!(eroded.contains(&"route"), "erosion findings: {eroded:?}");

    let release_hazards = rules_at(
        production_hazards(&report),
        "packages/deploy/scripts/release.sh",
    );
    for (line, rule) in [
        (3, "hardcoded-secret"),
        (11, "posix-sh-bashism"),
        (14, "pipe-download-to-shell"),
    ] {
        assert!(
            has_rule(&release_hazards, line, rule),
            "expected {rule} at line {line}: {release_hazards:?}"
        );
    }
    for path in ["packages/tools/build.bash", "packages/tools/setup.zsh"] {
        let hits = rules_at(production_hazards(&report), path);
        assert!(
            !hits.iter().any(|(_, rule)| rule == "posix-sh-bashism"),
            "bash and zsh scripts must not report POSIX sh bashisms: {path} {hits:?}"
        );
    }

    let release_flagged = rules_at(
        &prod["verbosity"]["findings"],
        "packages/deploy/scripts/release.sh",
    );
    for (line, rule) in [(12, "legacy-backticks"), (13, "useless-cat")] {
        assert!(
            has_rule(&release_flagged, line, rule),
            "expected {rule} at line {line}: {release_flagged:?}"
        );
    }

    for format in ["json", "toon", "markdown", "sarif"] {
        let output = run_stdout(repo.path(), &["check", "--format", format], 0);
        assert!(
            !output.contains(PLANTED_SECRET),
            "{format} output leaks the hardcoded secret: {output}"
        );
    }
}

#[test]
fn shell_workspace_packages_disabled_rules_filters_and_source_set_overrides() {
    let repo = shell_repo();
    let report = check_json(repo.path());

    let package_files: Vec<(&str, u64)> = report["source_sets"]["production"]["packages"]
        .as_array()
        .expect("packages")
        .iter()
        .map(|package| {
            (
                package["path"].as_str().expect("package path"),
                package["files"].as_u64().expect("package files"),
            )
        })
        .collect();
    assert!(
        package_files.contains(&("packages/deploy", 2))
            && package_files.contains(&("packages/tools", 2)),
        "expected shell files attributed to Workspace packages: {package_files:?}"
    );
    let scoped = run_json(repo.path(), &["check", "--package", "packages/tools"], 0);
    assert_eq!(
        scoped["source_sets"]["production"]["files"], 2,
        "scoped: {scoped}"
    );

    let disabled = check_json_with_config(
        repo.path(),
        r#"{"hazards":{"disabled_rules":["hardcoded-secret","posix-sh-bashism"]}}"#,
    );
    let disabled_rules: Vec<String> = rules_at(
        production_hazards(&disabled),
        "packages/deploy/scripts/release.sh",
    )
    .into_iter()
    .map(|(_, rule)| rule)
    .collect();
    assert!(
        !disabled_rules.iter().any(|rule| rule == "hardcoded-secret")
            && !disabled_rules.iter().any(|rule| rule == "posix-sh-bashism")
            && disabled_rules
                .iter()
                .any(|rule| rule == "pipe-download-to-shell"),
        "disabled_rules must silence only the named shell rules: {disabled_rules:?}"
    );

    let tools_without_zsh = json!({
        "languages": [{
            "plugin": "shell",
            "include": ["packages/tools"],
            "exclude": ["packages/tools/setup.zsh"]
        }]
    });
    let filtered = check_json_with_config(repo.path(), &tools_without_zsh.to_string());
    assert_eq!(
        filtered["source_sets"]["production"]["files"], 1,
        "filtered: {filtered}"
    );

    let tests_as_production = json!({ "source_sets": { "production": ["tests/**"] } });
    let overridden = check_json_with_config(repo.path(), &tests_as_production.to_string());
    assert_eq!(
        overridden["source_sets"]["production"]["files"], 5,
        "overridden: {overridden}"
    );
    assert_eq!(
        overridden["source_sets"]["test"]["files"], 1,
        "overridden: {overridden}"
    );
}

#[test]
fn shell_language_plugin_appears_in_schema_doctor_init_config_and_diff() {
    let repo = shell_repo();

    let schema = run_json(repo.path(), &["schema"], 0);
    let languages = schema["languages"].as_array().expect("schema languages");
    assert!(
        languages
            .iter()
            .any(|lang| lang["name"] == "shell"
                && lang["extensions"] == json!(["sh", "bash", "zsh"])),
        "expected shell in schema languages: {languages:?}"
    );

    assert_doctor_counts_language_files(repo.path(), "shell: 8");

    run_stdout(repo.path(), &["init"], 0);
    let starter =
        fs::read_to_string(repo.path().join("codeint.jsonc")).expect("read codeint.jsonc");
    assert!(
        starter.contains("\"plugin\": \"shell\""),
        "expected shell plugin in codeint.jsonc: {starter}"
    );
    let resolved = run_stdout(repo.path(), &["config", "--resolved"], 0);
    assert!(
        resolved.contains("shell"),
        "expected shell in resolved configuration: {resolved}"
    );
    check_json(repo.path());
    fs::remove_file(repo.path().join("codeint.jsonc")).expect("remove codeint.jsonc");

    write_repo_files(
        repo.path(),
        &[(
            "packages/tools/fetch.sh",
            "#!/bin/sh\nset -eu\nwget -qO- https://example.com/install.sh | sh\n",
        )],
    );
    let diff = run_json(repo.path(), &["diff", "HEAD"], 1);
    let new_hazards = diff["source_sets"]["production"]["hazards"]["new"]
        .as_array()
        .expect("new hazards");
    assert!(
        new_hazards
            .iter()
            .any(|finding| finding["path"] == "packages/tools/fetch.sh"
                && finding["rule"] == "pipe-download-to-shell"),
        "diff: {diff}"
    );
}
