use std::fs;
use std::path::Path;
use std::process::{Command, Output};

use serde_json::{Value, json};

use crate::common::{init_git_repo, run_codeint_json as run_json};

fn run_codeint(dir: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_codeint"))
        .args(args)
        .current_dir(dir)
        .output()
        .expect("run codeint")
}

fn run_stdout(dir: &Path, args: &[&str], expected_code: i32) -> String {
    let output = run_codeint(dir, args);
    assert_eq!(
        output.status.code(),
        Some(expected_code),
        "codeint {args:?} exited {:?}; stderr: {}",
        output.status.code(),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).expect("utf8 stdout")
}

fn check_json(dir: &Path) -> Value {
    run_json(dir, &["check"], 0)
}

fn set_config(dir: &Path, config_json: &str) {
    fs::write(dir.join("codeint.json"), config_json).expect("write codeint.json");
}

fn dep_finding_pairs(report: &Value, metric: &str) -> Vec<(String, String)> {
    report["dependencies"][metric]["findings"]
        .as_array()
        .expect("dependency findings")
        .iter()
        .map(|entry| {
            (
                entry["manifest"].as_str().expect("manifest").to_owned(),
                entry["dependency"].as_str().expect("dependency").to_owned(),
            )
        })
        .collect()
}

fn assert_dep_hygiene(
    report: &Value,
    expected_unused: &[(&str, &str)],
    expected_unlisted: &[(&str, &str)],
    expected_dev_in_prod: &[(&str, &str)],
) {
    let to_owned = |pairs: &[(&str, &str)]| -> Vec<(String, String)> {
        pairs
            .iter()
            .map(|(m, d)| ((*m).to_owned(), (*d).to_owned()))
            .collect()
    };
    assert_eq!(
        dep_finding_pairs(report, "unused_dependencies"),
        to_owned(expected_unused)
    );
    assert_eq!(
        dep_finding_pairs(report, "unlisted_dependencies"),
        to_owned(expected_unlisted)
    );
    assert_eq!(
        dep_finding_pairs(report, "dev_in_production_dependencies"),
        to_owned(expected_dev_in_prod)
    );
}

fn orphan_pairs(report: &Value) -> Vec<(&str, &str)> {
    report["source_sets"]["production"]["orphan_files"]["findings"]
        .as_array()
        .expect("orphan findings")
        .iter()
        .map(|entry| {
            (
                entry["path"].as_str().expect("orphan path"),
                entry["kind"].as_str().expect("orphan kind"),
            )
        })
        .collect()
}

#[test]
fn go_multi_module_workspace_cross_module_imports_source_sets_and_discovery() {
    let repo = init_git_repo(&[
        ("go.mod", "module example.com/acme\n\ngo 1.24\n"),
        (
            "services/billing/go.mod",
            "module example.com/acme/services/billing\n\ngo 1.24\n",
        ),
        (
            "cmd/app/main.go",
            concat!(
                "package main\n\n",
                "import \"C\"\n",
                "import (\n",
                "\t\"fmt\"\n",
                "\t\"example.com/acme/services/billing/invoice\"\n",
                ")\n\n",
                "func main() {\n",
                "\tfmt.Println(invoice.Format(invoice.Total(3)))\n",
                "}\n",
            ),
        ),
        (
            "services/billing/invoice/calc.go",
            concat!(
                "package invoice\n\n",
                "import \"example.com/acme/shared\"\n\n",
                "func Total(n int) int {\n",
                "\treturn shared.Scale(n)\n",
                "}\n",
            ),
        ),
        (
            "services/billing/invoice/format.go",
            concat!(
                "package invoice\n\n",
                "import \"fmt\"\n\n",
                "func Format(v int) string {\n",
                "\treturn fmt.Sprintf(\"%d\", v)\n",
                "}\n",
            ),
        ),
        (
            "shared/util.go",
            "package shared\n\nfunc Scale(n int) int {\n\treturn n * 2\n}\n",
        ),
        (
            "shared/util_test.go",
            "package shared\n\nfunc TestScale() int {\n\treturn Scale(2)\n}\n",
        ),
        (
            "shared/testdata/fixture.go",
            "package testdata\n\nfunc Sample() int {\n\treturn 9\n}\n",
        ),
        (
            "shared/gen.go",
            "// Code generated by mockgen. DO NOT EDIT.\npackage shared\n\nfunc Generated() int {\n\treturn 1\n}\n",
        ),
        (
            "vendor/example.org/dep/dep.go",
            "package dep\n\nfunc Vendored() int {\n\treturn 1\n}\n",
        ),
        ("web/view.ts", "export const ready = true;\n"),
    ]);

    let report = check_json(repo.path());
    let go_section = &report["languages"]["go"];
    assert_eq!(go_section["source_sets"]["production"]["files"], 4);
    assert_eq!(go_section["source_sets"]["test"]["files"], 2);
    assert_eq!(go_section["source_sets"]["generated"]["files"], 1);
    assert_eq!(go_section["source_sets"]["vendored"]["files"], 1);
    assert_eq!(
        go_section["source_sets"]["production"]["import_cycles"]["unresolved_imports"]["count"],
        0
    );

    let go_packages = go_section["source_sets"]["production"]["packages"]
        .as_array()
        .expect("go workspace packages");
    assert!(
        go_packages
            .iter()
            .any(|pkg| pkg["path"] == "services/billing" && pkg["files"] == 2),
        "expected services/billing Workspace package in {go_packages:?}"
    );

    let scoped = run_json(repo.path(), &["check", "--package", "services/billing"], 0);
    assert_eq!(scoped["files"], 2);
    assert_eq!(
        scoped["source_sets"]["production"]["import_cycles"]["unresolved_imports"]["count"],
        0
    );

    let schema = run_json(repo.path(), &["schema"], 0);
    let languages = schema["languages"].as_array().expect("schema languages");
    assert!(
        languages
            .iter()
            .any(|lang| lang["name"] == "go" && lang["extensions"] == json!(["go"])),
        "expected go in schema languages: {languages:?}"
    );

    let doctor = run_json(repo.path(), &["doctor"], 0);
    assert_eq!(doctor["summary"]["errors"], 0);
    let checks = doctor["checks"].as_array().expect("doctor checks");
    let lang_check = checks
        .iter()
        .find(|c| c["id"] == "languages")
        .expect("languages check");
    assert!(
        lang_check["summary"]
            .as_str()
            .unwrap_or_default()
            .contains("go:"),
        "expected go in doctor languages check: {lang_check}"
    );
    let ws_check = checks
        .iter()
        .find(|c| c["id"] == "workspace")
        .expect("workspace check");
    assert!(
        ws_check["detail"]
            .as_str()
            .unwrap_or_default()
            .contains("services/billing"),
        "expected services/billing in doctor workspace check: {ws_check}"
    );

    let init_out = run_stdout(repo.path(), &["init"], 0);
    assert!(init_out.contains("codeint.jsonc"));
    let init_cfg = fs::read_to_string(repo.path().join("codeint.jsonc")).expect("read init config");
    assert!(
        init_cfg.contains("\"plugin\": \"go\""),
        "expected go plugin in codeint.jsonc: {init_cfg}"
    );

    fs::remove_file(repo.path().join("codeint.jsonc")).expect("remove codeint.jsonc");
    set_config(
        repo.path(),
        r#"{"source_sets": {"generated": ["shared/util.go"]}}"#,
    );
    let overridden = check_json(repo.path());
    assert_eq!(
        overridden["languages"]["go"]["source_sets"]["production"]["files"],
        3
    );
    assert_eq!(
        overridden["languages"]["go"]["source_sets"]["generated"]["files"],
        2
    );
}

#[test]
fn go_metrics_measure_erosion_cognitive_duplication_and_verbosity_without_flagging_err_check() {
    let shared_body = concat!(
        "\ttotal := base + offset\n",
        "\tfor idx := 0; idx < limit; idx++ {\n",
        "\t\tstep := idx * factor + delta\n",
        "\t\tif step > ceiling {\n",
        "\t\t\ttotal += step - ceiling\n",
        "\t\t}\n",
        "\t\tif step%2 == 0 {\n",
        "\t\t\ttotal += step / 2\n",
        "\t\t}\n",
        "\t\ttotal ^= idx + salt\n",
        "\t}\n",
        "\tif total < floor {\n",
        "\t\ttotal = floor + offset\n",
        "\t}\n",
        "\treturn total * scale + bias\n",
    );
    let dup_a = format!(
        "package metrics\n\nfunc ComputeAlpha(base, offset, limit, factor, delta, ceiling, salt, floor, scale, bias int) int {{\n{shared_body}}}\n"
    );
    let dup_b = format!(
        "package metrics\n\nfunc ComputeBeta(base, offset, limit, factor, delta, ceiling, salt, floor, scale, bias int) int {{\n{shared_body}}}\n"
    );
    let complex_file = concat!(
        "package metrics\n\n",
        "type Router struct{}\n\n",
        "func (r *Router) Dispatch(a, b, c, d int, err error) (int, error) {\n",
        "\tif err != nil {\n",
        "\t\treturn 0, err\n",
        "\t}\n",
        "\tsum := 0\n",
        "\tfor i := 0; i < a; i++ {\n",
        "\t\tif i > b {\n",
        "\t\t\tif i > c {\n",
        "\t\t\t\tswitch d {\n",
        "\t\t\t\tcase 1:\n",
        "\t\t\t\t\tsum += 1\n",
        "\t\t\t\tcase 2:\n",
        "\t\t\t\t\tsum += 2\n",
        "\t\t\t\tcase 3:\n",
        "\t\t\t\t\tsum += 3\n",
        "\t\t\t\tcase 4:\n",
        "\t\t\t\t\tsum += 4\n",
        "\t\t\t\t}\n",
        "\t\t\t}\n",
        "\t\t}\n",
        "\t\tif a > 0 && b > 0 || c > 0 && d > 0 {\n",
        "\t\t\tsum += i\n",
        "\t\t}\n",
        "\t}\n",
        "\tif sum > 10 {\n",
        "\t\treturn sum, nil\n",
        "\t} else {\n",
        "\t\treturn -sum, nil\n",
        "\t}\n",
        "}\n\n",
        "func Cleanup(v int) {\n",
        "\t_ = v\n",
        "\treturn\n",
        "}\n",
    );

    let repo = init_git_repo(&[
        ("go.mod", "module example.com/metrics\n\ngo 1.24\n"),
        ("pkg/complex.go", complex_file),
        ("pkg/dup_a.go", &dup_a),
        ("pkg/dup_b.go", &dup_b),
    ]);

    let report = check_json(repo.path());
    let prod = &report["source_sets"]["production"];

    let eroded = prod["erosion"]["findings"]
        .as_array()
        .expect("erosion findings");
    assert!(
        eroded.iter().any(|f| f["name"] == "Router.Dispatch"
            && f["cyclomatic_complexity"].as_u64().unwrap_or(0) > 10),
        "expected Router.Dispatch in erosion findings: {eroded:?}"
    );

    let cognitive = prod["cognitive_complexity"]["findings"]
        .as_array()
        .expect("cognitive findings");
    assert!(
        cognitive.iter().any(|f| f["name"] == "Router.Dispatch"
            && f["cognitive_complexity"].as_u64().unwrap_or(0) > 15),
        "expected Router.Dispatch in cognitive findings: {cognitive:?}"
    );

    let clones = prod["duplication"]["clone_groups"]
        .as_array()
        .expect("clone groups");
    assert_eq!(clones.len(), 1, "expected one Go Clone group: {clones:?}");
    let clone_paths: Vec<&str> = clones[0]["locations"]
        .as_array()
        .expect("clone locations")
        .iter()
        .map(|loc| loc["path"].as_str().expect("location path"))
        .collect();
    assert_eq!(clone_paths, vec!["pkg/dup_a.go", "pkg/dup_b.go"]);

    let flagged = prod["verbosity"]["findings"]
        .as_array()
        .expect("verbosity findings");
    let rules: Vec<&str> = flagged
        .iter()
        .map(|f| f["rule"].as_str().expect("rule"))
        .collect();
    assert!(rules.contains(&"else-after-return"), "got {flagged:?}");
    assert!(rules.contains(&"trailing-bare-return"), "got {flagged:?}");
    assert!(
        !flagged
            .iter()
            .any(|f| f["path"] == "pkg/complex.go"
                && (6..=8).contains(&f["line"].as_u64().unwrap_or(0))),
        "if err != nil must never be flagged: {flagged:?}"
    );
}

#[test]
fn go_import_cycles_reports_zero_when_acyclic_and_detects_platform_specific_cycle() {
    let acyclic = init_git_repo(&[
        ("go.mod", "module example.com/acyclic\n\ngo 1.24\n"),
        (
            "pkg/a/a.go",
            "package a\n\nimport \"example.com/acyclic/pkg/b\"\n\nfunc Run() int { return b.Val() }\n",
        ),
        ("pkg/b/b.go", "package b\n\nfunc Val() int { return 1 }\n"),
    ]);
    let acyclic_report = check_json(acyclic.path());
    let acyclic_cycles = &acyclic_report["source_sets"]["production"]["import_cycles"];
    assert_eq!(acyclic_cycles["ratio"], 0.0);
    assert_eq!(acyclic_cycles["modules_in_import_cycles"], 0);
    assert_eq!(acyclic_cycles["modules"], 2);
    assert_eq!(acyclic_cycles["findings"], json!([]));

    let cyclic = init_git_repo(&[
        ("go.mod", "module example.com/plat\n\ngo 1.24\n"),
        (
            "pkg/a/a_linux.go",
            "package a\n\nimport \"example.com/plat/pkg/b\"\n\nfunc Linux() int { return b.Darwin() }\n",
        ),
        (
            "pkg/b/b_darwin.go",
            "package b\n\nimport \"example.com/plat/pkg/a\"\n\nfunc Darwin() int { return a.Linux() }\n",
        ),
        ("pkg/c/c.go", "package c\n\nfunc Plain() int { return 0 }\n"),
    ]);
    let cyclic_report = check_json(cyclic.path());
    let cycles = &cyclic_report["source_sets"]["production"]["import_cycles"];
    assert_eq!(cycles["modules_in_import_cycles"], 2);
    assert_eq!(cycles["modules"], 3);
    let findings = cycles["findings"].as_array().expect("cycle findings");
    assert_eq!(findings.len(), 1, "got {findings:?}");
    assert_eq!(
        findings[0]["modules"],
        json!(["pkg/a/a_linux.go", "pkg/b/b_darwin.go"])
    );
}

