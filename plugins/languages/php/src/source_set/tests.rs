use codeint_model::language::SourceSet;

use super::classify;

#[test]
fn classifies_generated_test_and_production_php_files() {
    assert_eq!(
        classify("src/Proxy.php", "// @generated by doctrine\n"),
        SourceSet::Generated
    );
    assert_eq!(
        classify("tests/ProxyTest.php", "/* DO NOT EDIT */\n"),
        SourceSet::Generated
    );
    for path in [
        "tests/Feature/AuthTest.php",
        "test/Unit/Helper.php",
        "app/Services/OrderTest.php",
        "src/order.test.php",
    ] {
        assert_eq!(classify(path, ""), SourceSet::Test, "{path}");
    }
    for path in [
        "app/Models/User.php",
        "src/Test.php",
        "src/TestingHelper.php",
    ] {
        assert_eq!(classify(path, ""), SourceSet::Production, "{path}");
    }
}
